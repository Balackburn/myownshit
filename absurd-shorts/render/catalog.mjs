// Prints the live catalogue (presets, clips, expressions, props, sets, creatures) as Markdown.
//   node render/catalog.mjs > ../.claude/skills/ce-mec-shorts/references/catalog.md
import { chromium, LAUNCH_ARGS } from './pw.mjs';
import { startServer } from './server.mjs';
const srv = await startServer();
const browser = await chromium.launch({ args: LAUNCH_ARGS });
const page = await browser.newPage();
await page.goto(`http://127.0.0.1:${srv.address().port}/render/stage.html?mode=export`);
await page.waitForFunction(() => window.__ready, null, { timeout: 60000 });
const C = await page.evaluate(async () => {
  const imp = async p => { try { return await import(p); } catch { return {}; } };
  const H = await imp('/engine/human.js'), A = await imp('/engine/animations.js'), F = await imp('/engine/face.js');
  const P = await imp('/engine/props.js'), S = await imp('/engine/sets.js'), Cr = await imp('/engine/creatures.js');
  const anchors = {}; for (const n of S.SET_NAMES || []) { try { anchors[n] = Object.keys(S.buildSet(n, {}).userData.anchors || {}); } catch { anchors[n] = ['(error)']; } }
  const presets = Object.entries(H.PRESETS || {}).map(([k, v]) => `\`${k}\` (${v.outfit}${v.hat && v.hat !== 'none' ? ', ' + v.hat : ''}${v.hair ? ', ' + v.hair : ''})`);
  return { presets, outfits: H.OUTFITS, hairs: H.HAIRS, hats: H.HATS, clips: A.CLIP_NAMES, expr: F.EXPRESSIONS, props: P.PROP_NAMES || [], sets: S.SET_NAMES || [], anchors, creatures: Cr.CREATURE_NAMES || [] };
});
const L = a => (a || []).map(x => '`' + x + '`').join(', ');
console.log(`# Catalogue (generated by render/catalog.mjs — do not edit by hand)

## Human presets (${C.presets.length})
${C.presets.join(', ')}

**Outfits**: ${L(C.outfits)}
**Hair**: ${L(C.hairs)}
**Hats**: ${L(C.hats)}

## Human clips (${C.clips.length})
${L(C.clips)}

## Expressions (${C.expr.length})
${L(C.expr)}

## Creatures (${C.creatures.length})
${L(C.creatures)}

## Props (${C.props.length})
${L(C.props)}

## Sets (${C.sets.length}) and anchors
${C.sets.map(s => `- \`${s}\`: ${(C.anchors[s] || []).join(', ')}`).join('\n')}
`);
await browser.close(); srv.close();
